# --- Local-First Persistence & Transparency Setup ---

def ensure_auth_secret():
    """Ensures a CHAINLIT_AUTH_SECRET exists and is persisted in .env."""
    env_path = ROOT_DIR / ".env"
    secret = os.environ.get("CHAINLIT_AUTH_SECRET")
    
    if not secret:
        # Check if it's in the .env file but not in environment
        if env_path.exists():
            with open(env_path, "r") as f:
                for line in f:
                    if line.startswith("CHAINLIT_AUTH_SECRET="):
                        secret = line.split("=")[1].strip()
                        os.environ["CHAINLIT_AUTH_SECRET"] = secret
                        break
        
        if not secret:
            secret = secrets.token_hex(32)
            os.environ["CHAINLIT_AUTH_SECRET"] = secret
            # Persist to .env
            mode = "a" if env_path.exists() else "w"
            with open(env_path, mode) as f:
                f.write(f"\n# Generated by IslamAI for local auth features\nCHAINLIT_AUTH_SECRET={secret}\n")
    return secret

# 1. Initialize Secrets
ensure_auth_secret()

# 2. Database Connection & Initialization
# Automated schema check/initialization on every startup
initialize_database(str(DB_PATH))

@cl.data_layer
def get_data_layer():
    return SQLAlchemyDataLayer(conninfo=DB_URL)

# 3. Transparent Authentication
# We return a fixed user object to bypass the login UI while enabling history features.
@cl.header_auth_callback
def header_auth_callback(headers: dict):
    return cl.User(identifier="local-user", metadata={"role": "admin"})

@cl.on_chat_resume
async def on_chat_resume(thread: dict):
    """Restores the LangGraph message history when a chat is resumed from the sidebar."""
    messages = []
    for step in thread.get("steps", []):
        if step.get("type") == "user_message":
            messages.append(HumanMessage(content=step.get("output")))
        elif step.get("type") == "assistant_message":
            messages.append(AIMessage(content=step.get("output")))
    
    cl.user_session.set("messages", messages)

